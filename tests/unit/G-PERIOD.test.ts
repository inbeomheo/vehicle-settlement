import { describe, expect, it } from 'vitest';
import { closingPeriod, closingPeriodLabel, seoulDate } from '../../src/shared/closing-period';

describe('회사 마감 기간', () => {
  it.each([
    ['2026-10-04', 19, 0, '2026-09-19', '2026-10-18'],
    ['2026-10-18', 19, 0, '2026-09-19', '2026-10-18'],
    ['2026-10-19', 19, 0, '2026-10-19', '2026-11-18'],
    ['2026-10-31', 19, -1, '2026-09-19', '2026-10-18'],
    ['2027-01-01', 19, 0, '2026-12-19', '2027-01-18'],
    ['2027-01-01', 19, -1, '2026-11-19', '2026-12-18'],
    ['2028-02-29', 28, 0, '2028-02-28', '2028-03-27'],
    ['2027-02-28', 28, -1, '2027-01-28', '2027-02-27'],
    ['2028-03-01', 1, -1, '2028-02-01', '2028-02-29'],
    ['2027-03-01', 1, -1, '2027-02-01', '2027-02-28'],
    ['2026-12-31', 1, 0, '2026-12-01', '2026-12-31'],
  ])('%s / %i일 / %i', (today, day, offset, from, to) => {
    expect(closingPeriod(today, day, offset)).toEqual({ from, to });
  });
  it('UTC 자정 대신 서울 자정으로 날짜를 계산한다', () => {
    expect(seoulDate(new Date('2026-10-18T14:59:59Z'))).toBe('2026-10-18');
    expect(seoulDate(new Date('2026-10-18T15:00:00Z'))).toBe('2026-10-19');
  });
  it('날짜 라벨과 달력 월 라벨을 구분한다', () => {
    expect(closingPeriodLabel('2026-10-04', 19)).toBe('이번 마감 (9/19~10/18)');
    expect(closingPeriodLabel('2026-10-04', 19, -1)).toBe('지난 마감 (8/19~9/18)');
    expect(closingPeriodLabel('2026-10-04', 1)).toBe('이번 달 (10/1~10/31)');
    expect(closingPeriodLabel('2026-10-04', 1, -1)).toBe('지난달 (9/1~9/30)');
  });
  it.each([0, 29, 1.5, NaN])('범위 밖 마감일 %s를 거부한다', (day) => {
    expect(() => closingPeriod('2026-10-04', day)).toThrow();
  });
});
